/** Tokens the position holds at price p (concentrated-liquidity maths, fees excluded). */
export function tokensAt(p: number) {
  const s = Math.min(Math.max(Math.sqrt(p), SA), SB);
  return { eth: L * (1 / s - 1 / SB), usdc: L * (s - SA) };
}

/** Linear interpolation of every column at time t (days). */
export function at(t: number) {
  const last = PATH[PATH.length - 1];
  if (t >= last[0]) return { t, px: last[1], lp: last[2], fees: last[3], hold: last[4] };
  let i = 0;
  while (PATH[i + 1][0] < t) i++;
  const a = PATH[i], b = PATH[i + 1];
  const f = (t - a[0]) / (b[0] - a[0]);
  const m = (k: number) => a[k] + (b[k] - a[k]) * f;
  return { t, px: m(1), lp: m(2), fees: m(3), hold: m(4) };
}

