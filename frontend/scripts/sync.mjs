// Copies deployed addresses (../deployments) and contract ABIs (../out) into lib/generated.
// Run after every deploy: npm run sync
// SYNC_DIR=deployments/fork npm run sync: use a rehearsal on a local fork instead (core and pools from there).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), "utf8"));

import { existsSync } from "node:fs";

// Every testnet we are deployed on: deployments/<name>-{core,tokens,pools,faucet}.json
const NETS = [
  { name: "sepolia", chainId: 11155111 },
  { name: "unichain-sepolia", chainId: 1301 },
];
const dir = process.env.SYNC_DIR ?? "deployments";
const chains = {};
for (const n of NETS) {
  const at = (what, d = "deployments") => `${d}/${n.name}-${what}.json`;
  if (!existsSync(new URL(at("core", dir), root))) continue;
  const core = read(at("core", dir));
  const tokens = read(at("tokens"));
  const pools = read(at("pools", dir));
  const faucet = read(at("faucet")).faucet;
  chains[n.chainId] = { chainId: n.chainId, name: n.name, core: { ...core, faucet }, tokens, pools };
}
const deployment = JSON.stringify({ chains }, null, 2);
writeFileSync(new URL("../lib/generated/deployment.json", import.meta.url), deployment);
// the backtest API reads our pools from here (api/_data is bundled with the Python function)
writeFileSync(new URL("../api/_data/deployment.json", import.meta.url), deployment + "\n");

const abi = (name) => read(`out/${name}.sol/${name}.json`).abi;
// The router has several overloads; keep only the single-pool exact-input swap.
const router = abi("IUniswapV4Router04").filter(
  (f) =>
    f.type === "function" &&
    f.name === "swapExactTokensForTokens" &&
    f.inputs.some((i) => i.name === "poolKey"),
);
// Rules' errors bubble up through the vault's calls (PriceMoved, InvalidSide, ...): add them so reverts decode.
const vaultAbi = abi("ConditionalOrders");
for (const e of abi("Rules").filter((x) => x.type === "error")) if (!vaultAbi.some((x) => x.type === "error" && x.name === e.name)) vaultAbi.push(e);
const out = [
  `// Generated by scripts/sync.mjs. Do not edit.`,
  `export const conditionalOrdersAbi = ${JSON.stringify(vaultAbi)} as const;`,
  `export const ruleHookAbi = ${JSON.stringify(abi("RuleHook"))} as const;`,
  `export const rulesAbi = ${JSON.stringify(abi("Rules"))} as const;`,
  `export const priceFeedsAbi = ${JSON.stringify(abi("PriceFeeds"))} as const;`,
  `export const testTokenAbi = ${JSON.stringify(abi("TestToken"))} as const;`,
  `export const routerAbi = ${JSON.stringify(router)} as const;`,
  `export const faucetAbi = ${JSON.stringify(abi("TestFaucet"))} as const;`,
  `export const mockAggregatorAbi = ${JSON.stringify(abi("MockAggregator"))} as const;`,
].join("\n\n");
writeFileSync(new URL("../lib/generated/abis.ts", import.meta.url), out + "\n");
for (const c of Object.values(chains)) console.log("synced", c.name, Object.keys(c.pools).length, "pools,", Object.keys(c.tokens).length, "tokens");
